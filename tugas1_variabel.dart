void main() {
  // Variabel untuk operasi hitung
  int angka1 = 10;
  int angka2 = 5;

  // Operasi penjumlahan
  print('Penjumlahan: ${angka1 + angka2}');

  // Operasi pengurangan
  print('Pengurangan: ${angka1 - angka2}');

  // Operasi perkalian
  print('Perkalian: ${angka1 * angka2}');

  // Operasi pembagian
  print('Pembagian: ${angka1 / angka2}');

  print('Exited');
}